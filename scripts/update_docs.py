#!/usr/bin/env python3
"""Fills the <!-- auto:NAME --> blocks in README.md and docs/ from an evidence folder.

  python3 scripts/update_docs.py --evidence .evidence [--ci-proof URL] [--run-url URL]

Images must already be in docs/images/. Blocks with nothing to show keep a note.
"""
import argparse
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
IMAGES = ROOT / "docs" / "images"
NOT_YET = "_Not generated yet. Run `bash loonie-rates-lab.sh evidence`._"


def fill(path, name, content):
    file = ROOT / path
    text = file.read_text(encoding="utf-8")
    pattern = re.compile(rf"(<!-- auto:{name} -->\n)(.*?)(\n<!-- /auto:{name} -->)", re.S)
    if not pattern.search(text):
        print(f"skip: no auto:{name} block in {path}")
        return
    file.write_text(pattern.sub(lambda m: m.group(1) + (content or NOT_YET) + m.group(3), text), encoding="utf-8")
    print(f"filled auto:{name} in {path}")


def gallery(items, prefix):
    present = [(f, caption) for f, caption in items if (IMAGES / f).exists()]
    if not present:
        return None
    header = "| " + " | ".join(caption for _, caption in present) + " |"
    rule = "|" + "---|" * len(present)
    row = "| " + " | ".join(f'<img src="{prefix}images/{f}" width="200" alt="{caption}">' for f, caption in present) + " |"
    return "\n".join([header, rule, row])


def read(path):
    return path.read_text(encoding="utf-8").strip() if path.exists() else None


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--evidence", required=True)
    parser.add_argument("--ci-proof", default="")
    parser.add_argument("--run-url", default="")
    args = parser.parse_args()
    evidence = pathlib.Path(args.evidence)

    fill("README.md", "gallery", gallery([
        ("light-01-rates.png", "Rates"),
        ("light-02-detail.png", "Detail and chart"),
        ("light-03-converter.png", "Converter"),
        ("dark-01-rates.png", "Dark Mode"),
    ], "docs/"))
    demo = IMAGES / "demo.gif"
    fill("README.md", "demo", '<img src="docs/images/demo.gif" width="280" alt="Loonie Rates demo">' if demo.exists() else None)
    fill("docs/day-3.md", "screens-day3", gallery([
        ("fr-01-rates.png", "French: rates"),
        ("fr-03-converter.png", "French: converter"),
        ("ax5-01-rates.png", "Largest text: rates"),
        ("ax5-02-detail.png", "Largest text: detail"),
        ("light-04-offline.png", "Offline banner"),
    ], ""))
    fill("docs/accessibility.md", "a11y-audit", read(evidence / "a11y-audit.md"))
    coverage = read(evidence / "coverage.md")
    fill("README.md", "coverage", coverage)
    fill("docs/day-3.md", "coverage", coverage)
    proof = None
    if args.ci_proof:
        proof = (f"[This throwaway pull request]({args.ci_proof}) added a deliberately failing test. "
                 "CI went red and GitHub blocked the merge, so the PR was closed unmerged.")
    fill("docs/day-3.md", "ci-proof", proof)
    if args.run_url:
        fill("docs/day-3.md", "run", f"Generated by [this Evidence workflow run]({args.run_url}).")


if __name__ == "__main__":
    main()
